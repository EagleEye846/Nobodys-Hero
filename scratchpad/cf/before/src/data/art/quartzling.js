// Shading, added over the drawn frames without moving a pixel: a bright rim
// down the lit side and along every top edge, a darker rim on the shadow
// side, the body growing deeper towards its feet, and a few pink and teal
// flecks where light bends inside the quartz.
function shade(rows) {
  const out = rows.map((r) => [...r]);
  rows.forEach((row, y) => {
    const first = row.search(/[^.]/);
    const last = row.length - 1 - [...row].reverse().findIndex((c) => c !== '.');
    if (first < 0) return;
    [...row].forEach((c, x) => {
      const up = rows[y - 1]?.[x];
      if (c === 'q' && (x === first + 1 || up === 'k')) out[y][x] = 'e';
      else if (c === 'Q' && up === 'k') out[y][x] = 'q';
      else if (c === 'z' && x === last - 1) out[y][x] = 'Z';
      else if (c === 'q' && y >= 18) out[y][x] = 'Q';
      else if (c === 'Q' && y >= 19) out[y][x] = 'z';
      else if (c === 'q' && y > 4 && y < 15 && x === first + 4) out[y][x] = 'Q';
      else if (c === 'Q' && y > 5 && y < 14 && (x * 3 + y * 5) % 17 === 0) out[y][x] = 'n';
      else if (c === 'z' && y > 6 && y < 17 && (x * 7 + y * 3) % 19 === 0) out[y][x] = 't';
    });
  });
  return out.map((r) => r.join(''));
}
