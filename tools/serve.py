"""Ruins Studio dev server: serves the game and lets the Studio save files.

Run it from anywhere:

    python tools/serve.py          (or: python tools/serve.py 8080 for another port)

Then open http://localhost:8000 for the game and http://localhost:8000/tools/
for the Studio. It only listens on this computer (127.0.0.1).

The Studio saves with POST /api/save. Saves may only write inside src/data/
and text/, and the previous version of any file is copied into
.studio-backups/ first. After every save the server rebuilds the generated
index files, so new enemies, rooms, songs, attack patterns and text files are
picked up by the game without editing any code:

    src/data/enemies/index.js    every enemy file in that folder
    src/data/rooms/index.js      every room file
    src/data/music/index.js      every song file
    src/data/patterns/index.js   every attack pattern made in the Pattern Lab
    src/data/textManifest.js     every .txt file under text/

Run `python tools/serve.py --generate` to rebuild those files without serving.
"""

import json
import re
import shutil
import sys
import time
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlparse

ROOT = Path(__file__).resolve().parent.parent
WRITABLE = ("src/data/", "text/")
BACKUPS = ROOT / ".studio-backups"
START_ROOM_ID = "ruins_entrance"

GENERATED_NOTE = (
    "// GENERATED by tools/serve.py from the files in this folder: don't edit it by\n"
    "// hand. Add or remove files here and the Studio server rebuilds it.\n"
)


def project_path(relative):
    """A project-relative path as an absolute Path, refusing anything outside the project."""
    relative = relative.replace("\\", "/").lstrip("/")
    path = (ROOT / relative).resolve()
    if path != ROOT and ROOT not in path.parents:
        raise ValueError(f"{relative} is outside the project")
    return path, relative


def is_writable(relative):
    if not relative.startswith(WRITABLE):
        return False
    # The generated files belong to this server.
    return not (relative.endswith("/index.js") or relative == "src/data/textManifest.js")


def identifier(stem):
    """A file name stem as a safe JavaScript identifier."""
    name = re.sub(r"\W", "_", stem)
    return f"_{name}" if name[0].isdigit() else name


def js_files(folder):
    path = ROOT / folder
    path.mkdir(parents=True, exist_ok=True)
    return sorted(f.stem for f in path.glob("*.js") if f.name != "index.js")


def write_if_changed(relative, text):
    path = ROOT / relative
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"  rebuilt {relative}")


def object_literal(entries):
    return f"{{ {entries} }}" if entries else "{}"


def imports(stems):
    return "".join(f"import * as {identifier(s)} from './{s}.js';\n" for s in stems)


def generate_enemies():
    stems = js_files("src/data/enemies")
    modules = ", ".join(f"'{s}': {identifier(s)}" for s in stems)
    write_if_changed("src/data/enemies/index.js", (
        f"{GENERATED_NOTE}{imports(stems)}\n"
        f"const MODULES = {object_literal(modules)};\n\n"
        "// Every enemy, keyed by its file name. Rooms refer to enemies by this id.\n"
        "export const ENEMIES = Object.fromEntries(\n"
        "  Object.entries(MODULES).map(([id, module]) => [id, Object.values(module).find((value) => value?.maxHp && value?.patterns)]),\n"
        ");\n"
    ))


def generate_rooms():
    stems = js_files("src/data/rooms")
    modules = ", ".join(identifier(s) for s in stems)
    write_if_changed("src/data/rooms/index.js", (
        f"{GENERATED_NOTE}{imports(stems)}\n"
        f"const MODULES = [{modules}];\n\n"
        "// Every room, by its id. Doors and saves refer to rooms by these ids.\n"
        "export const ROOMS = Object.fromEntries(\n"
        "  MODULES.flatMap((module) => Object.values(module))\n"
        "    .filter((value) => value?.id && value?.tiles)\n"
        "    .map((room) => [room.id, room]),\n"
        ");\n\n"
        "// The room a new game starts in.\n"
        f"export const START_ROOM = ROOMS.{START_ROOM_ID};\n"
    ))


def generate_music():
    stems = js_files("src/data/music")
    # battleTheme.js is played as 'battle'.
    modules = ", ".join(f"'{re.sub(r'Theme$', '', s)}': {identifier(s)}" for s in stems)
    write_if_changed("src/data/music/index.js", (
        f"{GENERATED_NOTE}{imports(stems)}\n"
        f"const MODULES = {object_literal(modules)};\n\n"
        "// Every song, keyed by its file name without \"Theme\" (battleTheme.js is 'battle').\n"
        "export const SONGS = Object.fromEntries(\n"
        "  Object.entries(MODULES).map(([name, module]) => [name, Object.values(module).find((value) => value?.sections && value?.instruments)]),\n"
        ");\n"
    ))


def generate_patterns():
    stems = js_files("src/data/patterns")
    modules = ", ".join(f"'{s}': {identifier(s)}" for s in stems)
    write_if_changed("src/data/patterns/index.js", (
        f"{GENERATED_NOTE}{imports(stems)}\n"
        f"const MODULES = {object_literal(modules)};\n\n"
        "// Attack patterns made in the Pattern Lab, keyed by file name. Each file's\n"
        "// default export is a factory: (box, density, tools) => ({ duration, update }).\n"
        "export const CUSTOM_PATTERNS = Object.fromEntries(\n"
        "  Object.entries(MODULES).map(([name, module]) => [name, module.default]),\n"
        ");\n"
    ))


def generate_text_manifest():
    text = ROOT / "text"
    files = sorted(p.relative_to(text).as_posix() for p in text.rglob("*.txt") if p.name != "README.txt")
    entries = "".join(f"  '{f}',\n" for f in files)
    write_if_changed("src/data/textManifest.js", (
        "// GENERATED by tools/serve.py: every .txt file under text/ (except README.txt).\n"
        "// The game loads them all at startup. Run the Studio server, or\n"
        "// `python tools/serve.py --generate`, after adding a text file by hand.\n"
        f"export const TEXT_FILES = [\n{entries}];\n"
    ))


def generate_all():
    generate_enemies()
    generate_rooms()
    generate_music()
    generate_patterns()
    generate_text_manifest()


class StudioHandler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT), **kwargs)

    # Always serve fresh files, so a refresh shows what was just saved.
    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def send_json(self, status, payload):
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        url = urlparse(self.path)
        if url.path == "/api/list":
            # Files in one project folder, e.g. /api/list?dir=src/data/enemies
            try:
                folder, _ = project_path(parse_qs(url.query).get("dir", [""])[0])
                files = sorted(p.name for p in folder.iterdir() if p.is_file()) if folder.is_dir() else []
                self.send_json(200, {"ok": True, "files": files})
            except ValueError as error:
                self.send_json(400, {"ok": False, "error": str(error)})
            return
        if url.path == "/api/ping":
            self.send_json(200, {"ok": True})
            return
        super().do_GET()

    def do_POST(self):
        if urlparse(self.path).path != "/api/save":
            self.send_json(404, {"ok": False, "error": "Unknown endpoint"})
            return
        try:
            length = int(self.headers.get("Content-Length", 0))
            request = json.loads(self.rfile.read(length).decode("utf-8"))
            path, relative = project_path(request["path"])
            if not is_writable(relative):
                raise ValueError(f"The Studio can't write {relative} (only src/data/ and text/)")
            content = request["content"]
            if not isinstance(content, str):
                raise ValueError("content must be text")

            if path.exists():
                backup = BACKUPS / time.strftime("%Y-%m-%d_%H-%M-%S") / relative
                backup.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, backup)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"saved {relative}")
            generate_all()
            self.send_json(200, {"ok": True, "path": relative})
        except (KeyError, ValueError, json.JSONDecodeError) as error:
            self.send_json(400, {"ok": False, "error": str(error)})
        except OSError as error:
            self.send_json(500, {"ok": False, "error": str(error)})


def main():
    generate_all()
    if "--generate" in sys.argv:
        return
    port = next((int(a) for a in sys.argv[1:] if a.isdigit()), 8000)
    server = ThreadingHTTPServer(("127.0.0.1", port), StudioHandler)
    print(f"Game:   http://localhost:{port}/")
    print(f"Studio: http://localhost:{port}/tools/")
    print("Press Ctrl+C to stop.")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
