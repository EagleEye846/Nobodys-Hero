//   hush_prowl_free  the same without the umbrella; hush_prowl_free_right, going right
//   hush_wait        standing still with the umbrella, breathing
//   hush_stand       standing, breathing hard (after the fight)
//   hush_lying       lying along the Warden's shoulder, the umbrella by its jaws, breathing
//   hush_lying_free  lying on the paving, head up, watching
//   hush_lie_down    going down onto its belly, slowly (once); hush_get_up, the reverse
//   hush_death       its forelegs fold, it goes down, breathes, and the ember goes out (once)
//

