// on their tile's bottom edge, centred), and use PROP_PALETTE's colours plus
// the few extra below. The forest ones are kept dark and low-contrast like the
// leaf litter, so the things that matter (chalk, treadles, trees you can chop,
// cut wood) are the bright bits that catch your eye.

